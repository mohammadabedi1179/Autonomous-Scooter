def parse_float_list(text):
    if text is None or str(text).strip() == "":
        return []
    return [float(x.strip()) for x in str(text).split(",") if x.strip()]


def clean_numeric(df, columns=None):
    if columns is None:
        columns = df.columns
    for col in columns:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce")
    return df


def arr(df, col):
    """Return a 1-D NumPy array for matplotlib compatibility."""
    return df[col].to_numpy(dtype=float)


def finite_last(x, y):
    mask = np.isfinite(x) & np.isfinite(y)
    if not np.any(mask):
        return None, None
    return x[mask][-1], y[mask][-1]


def continuous_error_deg(measured, target):
    """Simple continuous error. Use this for unwrapped/continuous heading."""
    if not np.isfinite(measured):
        return np.nan
    return measured - target


def robust_median(s):
    s = pd.to_numeric(s, errors="coerce").dropna()
    return float(s.median()) if len(s) else np.nan


def robust_min(s):
    s = pd.to_numeric(s, errors="coerce").dropna()
    return float(s.min()) if len(s) else np.nan


def robust_max(s):
    s = pd.to_numeric(s, errors="coerce").dropna()
    return float(s.max()) if len(s) else np.nan


