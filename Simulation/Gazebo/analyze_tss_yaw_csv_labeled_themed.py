def summarize_windows(df, windows):
    rows = []

    deg_cols = [
        "euler_yaw_deg",
        "quat_heading_deg",
        "gyro_heading_deg",
        "quat_heading_wrapped_deg",
        "euler_yaw_wrapped_deg",
    ]
    other_cols = [
        "mag_norm_gauss",
        "pitch_deg",
        "roll_deg",
        "mx_gauss", "my_gauss", "mz_gauss",
        "gx_rad_s", "gy_rad_s", "gz_rad_s",
    ]

    for w in windows:
        target = w["target_deg"]
        mask = (df["time_s"] >= w["summary_start_s"]) & (df["time_s"] <= w["summary_end_s"])
        sub = df.loc[mask].copy()

        row = {
            "target_deg": target,
            "window_start_s": w["start_s"],
            "window_end_s": w["end_s"],
            "summary_start_s": w["summary_start_s"],
            "summary_end_s": w["summary_end_s"],
            "center_s": w["center_s"],
            "n_samples": int(len(sub)),
            "window_method": w["method"],
        }

        for col in deg_cols:
            if col in sub.columns:
                med = robust_median(sub[col])
                row[f"{col}_median"] = med
                row[f"{col}_error"] = continuous_error_deg(med, target)
                row[f"{col}_min"] = robust_min(sub[col])
                row[f"{col}_max"] = robust_max(sub[col])
                row[f"{col}_range"] = row[f"{col}_max"] - row[f"{col}_min"] if np.isfinite(row[f"{col}_max"]) and np.isfinite(row[f"{col}_min"]) else np.nan

        for col in other_cols:
            if col in sub.columns:
                row[f"{col}_median"] = robust_median(sub[col])
                row[f"{col}_min"] = robust_min(sub[col])
                row[f"{col}_max"] = robust_max(sub[col])
                row[f"{col}_range"] = row[f"{col}_max"] - row[f"{col}_min"] if np.isfinite(row[f"{col}_max"]) and np.isfinite(row[f"{col}_min"]) else np.nan

        rows.append(row)

    return pd.DataFrame(rows)


