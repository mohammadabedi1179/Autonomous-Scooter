def contiguous_segments(mask):
    """Return inclusive index segments for a boolean mask."""
    idx = np.flatnonzero(mask)
    if len(idx) == 0:
        return []

    segments = []
    start = idx[0]
    prev = idx[0]
    for i in idx[1:]:
        if i == prev + 1:
            prev = i
        else:
            segments.append((start, prev))
            start = i
            prev = i
    segments.append((start, prev))
    return segments


def shrink_window(start_t, end_t, shrink_fraction):
    """Shrink a window symmetrically for cleaner median calculation."""
    if end_t <= start_t:
        return start_t, end_t
    width = end_t - start_t
    margin = width * shrink_fraction
    return start_t + margin, end_t - margin


def windows_from_manual_centers(df, targets, centers, hold_width, shrink_fraction):
    if len(centers) != len(targets):
        raise ValueError("Number of --checkpoint-centers must match number of --targets.")

    t_min = float(df["time_s"].min())
    t_max = float(df["time_s"].max())
    windows = []
    half = hold_width / 2.0
    for target, center in zip(targets, centers):
        start = max(t_min, center - half)
        end = min(t_max, center + half)
        s2, e2 = shrink_window(start, end, shrink_fraction)
        windows.append({
            "target_deg": target,
            "start_s": start,
            "end_s": end,
            "summary_start_s": s2,
            "summary_end_s": e2,
            "center_s": center,
            "method": "manual_center",
        })
    return windows


def windows_by_reference_target(df, targets, reference_col, tolerance_deg, min_duration_s, shrink_fraction):
    """
    Auto-detect hold windows by finding the longest time segment where
    reference_col is near each target.

    This works well for step-like tests: 0 -> 90 -> 180 -> 270 -> 360.
    It is intentionally simple and transparent.
    """
    if reference_col not in df.columns:
        raise ValueError(f"Reference column '{reference_col}' not found in CSV.")

    t = arr(df, "time_s")
    y = arr(df, reference_col)
    finite = np.isfinite(t) & np.isfinite(y)

    windows = []
    used_ranges = []

    for target in targets:
        dist = np.abs(y - target)
        mask = finite & (dist <= tolerance_deg)
        segments = contiguous_segments(mask)

        candidates = []
        for a, b in segments:
            start_t = float(t[a])
            end_t = float(t[b])
            duration = end_t - start_t
            if duration < min_duration_s:
                continue
            med = float(np.nanmedian(y[a:b + 1]))
            err = abs(med - target)
            candidates.append((duration, -err, a, b, med))

        if candidates:
            # Prefer longest hold; if tied, closest median.
            candidates.sort(reverse=True)
            _, _, a, b, med = candidates[0]
            start = float(t[a])
            end = float(t[b])
            center = 0.5 * (start + end)
            method = f"auto_near_{reference_col}"
        else:
            # Fallback: nearest single point, then create a hold_width window.
            valid_idx = np.flatnonzero(finite)
            if len(valid_idx) == 0:
                continue
            nearest = valid_idx[np.nanargmin(np.abs(y[valid_idx] - target))]
            center = float(t[nearest])
            half = max(min_duration_s, 2.0) / 2.0
            start = max(float(t[0]), center - half)
            end = min(float(t[-1]), center + half)
            method = f"fallback_nearest_{reference_col}"

        s2, e2 = shrink_window(start, end, shrink_fraction)
        windows.append({
            "target_deg": target,
            "start_s": start,
            "end_s": end,
            "summary_start_s": s2,
            "summary_end_s": e2,
            "center_s": center,
            "method": method,
        })
        used_ranges.append((start, end))

    windows.sort(key=lambda w: w["center_s"])
    return windows


