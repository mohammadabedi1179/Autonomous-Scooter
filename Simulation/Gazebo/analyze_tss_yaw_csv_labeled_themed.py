def main():
    parser = argparse.ArgumentParser(description="Create labeled TSS yaw desk-test plots and summary CSV.")
    parser.add_argument("csv", help="Input CSV file from the TSS logger.")
    parser.add_argument("--outdir", default="tss_analysis_labeled", help="Output directory.")
    parser.add_argument("--targets", default=",".join(str(x) for x in DEFAULT_TARGETS), help="Comma-separated physical target angles, e.g. 0,90,180,270,360")
    parser.add_argument("--checkpoint-centers", default=None, help="Optional comma-separated center times for each target window.")
    parser.add_argument("--hold-width", type=float, default=5.0, help="Window width in seconds when using manual centers.")
    parser.add_argument("--reference-col", default="euler_yaw_deg", help="Column used to auto-detect windows.")
    parser.add_argument("--window-tolerance-deg", type=float, default=25.0, help="Auto-window tolerance around target angle.")
    parser.add_argument("--min-window-duration", type=float, default=1.0, help="Minimum duration for auto-detected window.")
    parser.add_argument("--summary-shrink", type=float, default=0.18, help="Fraction removed from each side for median calculation; 0.18 means use central 64%%.")
    parser.add_argument("--theme", default="thesis_nude_contrast", choices=list(THEMES.keys()), help="Plot theme copied from training_analysis_creative_static.py.")
    args = parser.parse_args()

    csv_path = Path(args.csv)
    outdir = Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)

    targets = parse_float_list(args.targets)
    centers = parse_float_list(args.checkpoint_centers) if args.checkpoint_centers else []

    df = pd.read_csv(csv_path)
    df = clean_numeric(df)

    if "time_s" not in df.columns:
        raise RuntimeError("CSV must contain 'time_s'.")

    # Derived pitch/roll degrees if rad columns are present.
    if "pitch_rad" in df.columns and "pitch_deg" not in df.columns:
        df["pitch_deg"] = np.degrees(pd.to_numeric(df["pitch_rad"], errors="coerce"))
    if "roll_rad" in df.columns and "roll_deg" not in df.columns:
        df["roll_deg"] = np.degrees(pd.to_numeric(df["roll_rad"], errors="coerce"))

    # Remove rows with invalid time.
    df = df[np.isfinite(df["time_s"].to_numpy(dtype=float))].copy()
    df = df.sort_values("time_s").reset_index(drop=True)

    setup_style(args.theme)

    if centers:
        windows = windows_from_manual_centers(df, targets, centers, args.hold_width, args.summary_shrink)
    else:
        windows = windows_by_reference_target(
            df, targets, args.reference_col,
            args.window_tolerance_deg,
            args.min_window_duration,
            args.summary_shrink,
        )

    stem = csv_path.stem
    yaw_path = outdir / f"{stem}_yaw_comparison.png"
    mag_path = outdir / f"{stem}_mag_norm.png"
    pr_path = outdir / f"{stem}_pitch_roll.png"
    summary_path = outdir / f"{stem}_summary.csv"

    plot_yaw_comparison(df, windows, yaw_path)
    plot_mag_norm(df, windows, mag_path)
    plot_pitch_roll(df, windows, pr_path)

    summary = summarize_windows(df, windows)
    summary.to_csv(summary_path, index=False)

    print("Saved:")
    print(f"  {yaw_path}")
    print(f"  {mag_path}")
    print(f"  {pr_path}")
    print(f"  {summary_path}")
    print("\nDetected/used windows:")
    for w in windows:
        print(
            f"  target={w['target_deg']:7.2f} deg | "
            f"window={w['start_s']:7.3f}..{w['end_s']:7.3f} s | "
            f"summary={w['summary_start_s']:7.3f}..{w['summary_end_s']:7.3f} s | "
            f"method={w['method']}"
        )


if __name__ == "__main__":
    main()
