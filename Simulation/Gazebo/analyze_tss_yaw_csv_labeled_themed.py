def add_windows(ax, windows, label_y_frac=0.965):
    """Shade checkpoint windows and label target angles at top using the active theme."""
    y0, y1 = ax.get_ylim()
    label_y = y0 + label_y_frac * (y1 - y0)

    band_colors = STAGE_BAND_COLORS if "STAGE_BAND_COLORS" in globals() else [EDGE_CLR]
    for i, w in enumerate(windows):
        band = band_colors[i % len(band_colors)]
        ax.axvspan(w["start_s"], w["end_s"], alpha=0.62, color=band, linewidth=0, zorder=0)
        ax.axvline(w["start_s"], color=EDGE_CLR, alpha=0.70, linewidth=0.8, zorder=1)
        ax.axvline(w["end_s"], color=EDGE_CLR, alpha=0.70, linewidth=0.8, zorder=1)
        ax.text(
            w["center_s"], label_y,
            f'{w["target_deg"]:.0f}° window',
            ha="center", va="top", fontsize=8.5, color=TEXT_CLR,
            bbox=themed_bbox(alpha=0.86, pad=0.24),
            zorder=8,
        )


def add_direct_label(ax, x, y, label, color=None, dy=0.0):
    x_last, y_last = finite_last(x, y)
    if x_last is None:
        return
    x0, x1 = ax.get_xlim()
    x_pad = 0.008 * (x1 - x0)
    ax.text(
        x_last + x_pad,
        y_last + dy,
        f"{label}: {y_last:.1f}",
        va="center", ha="left", fontsize=8.5,
        color=color if color is not None else TEXT_CLR,
        bbox=themed_bbox(alpha=0.88, pad=0.18),
        clip_on=False,
        zorder=10,
    )


def annotate_window_medians(ax, df, windows, cols, y_offsets=None, suffix="°", colors=None):
    if y_offsets is None:
        y_offsets = [0.0] * len(cols)
    if colors is None:
        colors = theme_color_cycle()

    for w in windows:
        mask = (df["time_s"] >= w["summary_start_s"]) & (df["time_s"] <= w["summary_end_s"])
        sub = df.loc[mask]
        if len(sub) == 0:
            continue
        for i, (col, yoff) in enumerate(zip(cols, y_offsets)):
            if col not in sub.columns:
                continue
            med = robust_median(sub[col])
            if not np.isfinite(med):
                continue
            c = colors[i % len(colors)]
            ax.scatter([w["center_s"]], [med], s=32, zorder=7,
                       color=c, edgecolors=PAPER_WHITE, linewidths=0.75)
            ax.text(
                w["center_s"], med + yoff,
                f"{med:.1f}{suffix}",
                ha="center", va="bottom" if yoff >= 0 else "top", fontsize=8,
                color=TEXT_CLR,
                bbox=themed_bbox(alpha=0.88, pad=0.15),
                zorder=9,
            )


def finalize_axes(ax, xlabel="Time [s]", ylabel=None, title=None):
    if title:
        ax.set_title(title, color=TEXT_CLR, pad=12)
    ax.set_xlabel(xlabel, color=TEXT_CLR)
    if ylabel:
        ax.set_ylabel(ylabel, color=TEXT_CLR)
    ax.grid(True, color=GRID_CLR, alpha=0.82, linewidth=0.45)
    ax.margins(x=0.02)
    for spine in ax.spines.values():
        spine.set_color(EDGE_CLR)
        spine.set_linewidth(0.8)

